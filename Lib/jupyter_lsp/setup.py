import json

from libs import inline_verification_step, simple_library, source_path, transform_source_text, write_source_text


def embed_jupyter_lsp_schema(context) -> None:
    schema_path = source_path(context, "Lib/jupyter_lsp/schema/schema.json")
    schema = json.loads(schema_path.read_text(encoding="utf-8"))
    config_dir = source_path(context, "Lib/jupyter_lsp/specs/config")
    config_schemas = {
        config_path.name.removesuffix(".schema.json"): json.loads(config_path.read_text(encoding="utf-8"))
        for config_path in sorted(config_dir.glob("*.schema.json"))
    }

    write_source_text(
        context,
        "Lib/jupyter_lsp/schema/_staticpython_schema.py",
        "# Generated by StaticPython; keeps jupyter-lsp schema data available after freezing.\n"
        f"SCHEMA = {schema!r}\n",
    )
    write_source_text(
        context,
        "Lib/jupyter_lsp/specs/config/_staticpython_config_schemas.py",
        "# Generated by StaticPython; keeps jupyter-lsp config schemas available after freezing.\n"
        f"CONFIG_SCHEMAS = {config_schemas!r}\n",
    )

    def patch_schema_init(text: str) -> str:
        return text.replace(
            "import json\n"
            "import pathlib\n"
            "\n"
            "import jsonschema\n"
            "\n"
            "HERE = pathlib.Path(__file__).parent\n"
            "SCHEMA_FILE = HERE / \"schema.json\"\n"
            "SCHEMA = json.loads(SCHEMA_FILE.read_text(encoding=\"utf-8\"))\n",
            "import jsonschema\n\nfrom ._staticpython_schema import SCHEMA\n",
            1,
        )

    transform_source_text(context, "Lib/jupyter_lsp/schema/__init__.py", patch_schema_init)

    def patch_config_init(text: str) -> str:
        return text.replace(
            "import json\n"
            "import pathlib\n"
            "\n"
            "CONFIGS = pathlib.Path(__file__).parent\n"
            "\n"
            "\n"
            "def load_config_schema(key):\n"
            "    \"\"\"load a keyed filename\"\"\"\n"
            "    return json.loads(\n"
            "        (CONFIGS / \"{}.schema.json\".format(key)).read_text(encoding=\"utf-8\")\n"
            "    )\n",
            "import json\n"
            "import pathlib\n"
            "\n"
            "from ._staticpython_config_schemas import CONFIG_SCHEMAS\n"
            "\n"
            "CONFIGS = pathlib.Path(__file__).parent\n"
            "\n"
            "\n"
            "def load_config_schema(key):\n"
            "    \"\"\"load a keyed filename\"\"\"\n"
            "    schema = CONFIG_SCHEMAS.get(key)\n"
            "    if schema is not None:\n"
            "        return schema\n"
            "    return json.loads(\n"
            "        (CONFIGS / \"{}.schema.json\".format(key)).read_text(encoding=\"utf-8\")\n"
            "    )\n",
            1,
        )

    transform_source_text(context, "Lib/jupyter_lsp/specs/config/__init__.py", patch_config_init)


LIBRARY_INTEGRATION = simple_library(
    name="jupyter_lsp",
    project_name="jupyter-lsp",
    overlay_entries=["Lib/jupyter_lsp"],
    materialized_paths=[
        "Lib/jupyter_lsp/schema/schema.json",
        "Lib/jupyter_lsp/schema/_staticpython_schema.py",
        "Lib/jupyter_lsp/specs/config/_staticpython_config_schemas.py",
    ],
    verification_materialized_paths=[
        "Lib/jupyter_lsp",
        "Lib/jupyter_lsp/schema/schema.json",
        "Lib/jupyter_lsp/specs/config/pylsp.schema.json",
        "Lib/jupyter_lsp/specs/config/pyright.schema.json",
    ],
    post_patch_hooks=[embed_jupyter_lsp_schema],
    verification_steps=[
        inline_verification_step(
            "jupyter-lsp-smoke",
            """
from jupyter_lsp.manager import LanguageServerManager
from jupyter_lsp.schema import LANGUAGE_SERVER_SPEC, LANGUAGE_SERVER_SPEC_MAP, SERVERS_RESPONSE

spec = {
    "version": 2,
    "argv": ["pylsp"],
    "languages": ["python"],
    "display_name": "Python LSP",
    "mime_types": ["text/x-python"],
    "requires_documents_on_disk": False,
}

LANGUAGE_SERVER_SPEC.validate(spec)
LANGUAGE_SERVER_SPEC_MAP.validate({"pylsp": spec})
SERVERS_RESPONSE.validate({"version": 2, "sessions": {}, "specs": {"pylsp": spec}})

manager = LanguageServerManager()
assert manager.virtual_documents_dir == ".virtual_documents"
assert manager.language_servers == {}
assert manager.conf_d_language_servers == {}
""",
        )
    ],
)
