    transform_first_existing_source_text(
        context,
        ["Lib/plotly/widgets/graph_widget.py"],
        patch_graph_widget,
        allow_all_missing=True,
    )

    def patch_data(text):
        if not text:
            return text
        import_guard = (
            "try:\n"
            "    from plotly._staticpython_package_data import DATASETS as _STATICPYTHON_DATASETS\n"
            "except Exception:\n"
            "    _STATICPYTHON_DATASETS = {}\n\n"
        )
        if "_STATICPYTHON_DATASETS" not in text:
            if text.startswith('"""'):
                end = text.find('"""\n', 3)
                if end != -1:
                    insert_at = end + 4
                    text = text[:insert_at] + "\nimport gzip\nimport io\nimport json\nimport os\n\n" + import_guard + text[insert_at:]
            elif text.startswith("'''"):
                end = text.find("'''\n", 3)
                if end != -1:
                    insert_at = end + 4
                    text = text[:insert_at] + "\nimport gzip\nimport io\nimport json\nimport os\n\n" + import_guard + text[insert_at:]
            elif "import os\n" in text:
                text = text.replace("import os\n", "import gzip\nimport io\nimport json\nimport os\n" + import_guard, 1)
            else:
                text = "import gzip\nimport io\nimport json\nimport os\n\n" + import_guard + text

        if "def _get_dataset(d):" in text and "dataset_candidates = [" not in text:
            text = replace_function_block_once(
                text,
                "_get_dataset",
                'def _get_dataset(d):\n'
                '    import pandas\n\n'
                '    dataset_name = d + ".csv.gz"\n'
                '    dataset_bytes = _STATICPYTHON_DATASETS.get(dataset_name)\n'
                '    if dataset_bytes is not None:\n'
                '        return pandas.read_csv(io.BytesIO(gzip.decompress(dataset_bytes)))\n\n'
                '    dataset_candidates = [\n'
                '        os.path.join(\n'
                '            os.path.dirname(os.path.dirname(__file__)),\n'
                '            "package_data",\n'
                '            "datasets",\n'
                '            dataset_name,\n'
                '        ),\n'
                '        os.path.join(os.path.dirname(__file__), dataset_name),\n'
                '    ]\n'
                '    for filepath in dataset_candidates:\n'
                '        if os.path.exists(filepath):\n'
                '            return pandas.read_csv(filepath)\n'
                '    raise FileNotFoundError(dataset_name)\n\n',
                label="plotly dataset loader fallback",
                next_name=None,
            )

        if "def election_geojson():" in text and 'geojson_bytes = _STATICPYTHON_DATASETS.get("election.geojson.gz")' not in text:
            text = replace_function_block_once(
                text,
                "election_geojson",
                'def election_geojson():\n'
                '    """\n'
                'Each feature represents an electoral district in the 2013 Montreal mayoral election.\n\n'
                'Returns:\n'
                '    A GeoJSON-formatted `dict`.\n'
                '    """\n'
                '    geojson_name = "election.geojson.gz"\n'
                '    geojson_bytes = _STATICPYTHON_DATASETS.get(geojson_name)\n'
                '    if geojson_bytes is not None:\n'
                '        with gzip.GzipFile(fileobj=io.BytesIO(geojson_bytes), mode="r") as f:\n'
                '            return json.loads(f.read().decode("utf-8"))\n\n'
                '    dataset_candidates = [\n'
                '        os.path.join(\n'
                '            os.path.dirname(os.path.dirname(__file__)),\n'
                '            "package_data",\n'
                '            "datasets",\n'
                '            geojson_name,\n'
                '        ),\n'
                '        os.path.join(os.path.dirname(__file__), geojson_name),\n'
                '    ]\n'
                '    for filepath in dataset_candidates:\n'
                '        if os.path.exists(filepath):\n'
                '            with gzip.GzipFile(filepath, "r") as f:\n'
                '                return json.loads(f.read().decode("utf-8"))\n'
                '    raise FileNotFoundError(geojson_name)\n\n',
                label="plotly election geojson loader fallback",
                next_name=None,
            )

        return text

    transform_source_text(context, "Lib/plotly/data/__init__.py", patch_data, allow_missing=True)

    def patch_validator_cache(text):
        if "_validators.json" not in text:
            return text
        import_guard = (
            "try:\n"
            "    from plotly._staticpython_validators import VALIDATORS as _STATICPYTHON_VALIDATORS\n"
            "except Exception:\n"
            "    _STATICPYTHON_VALIDATORS = None\n\n"
        )
        if "_STATICPYTHON_VALIDATORS" not in text:
            text = text.replace("import os.path as opath\n", "import os.path as opath\n" + import_guard, 1)

        old = (
            "        if ValidatorCache._json_cache is None:\n"
            "            # Load the JSON validator params from the file\n"
            "            validator_json_path = opath.join(\n"
            "                opath.dirname(__file__), \"validators\", \"_validators.json\"\n"
            "            )\n"
            "            if not opath.exists(validator_json_path):\n"
            "                raise FileNotFoundError(\n"
            "                    f\"Validator JSON file not found: {validator_json_path}\"\n"
            "                )\n"
            "            with open(validator_json_path, \"r\") as f:\n"
            "                ValidatorCache._json_cache = json.load(f)\n"
        )
        new = (
            "        if ValidatorCache._json_cache is None:\n"
            "            if _STATICPYTHON_VALIDATORS is not None:\n"
            "                ValidatorCache._json_cache = _STATICPYTHON_VALIDATORS\n"
            "            else:\n"
            "                # Load the JSON validator params from the file\n"
            "                validator_json_path = opath.join(\n"
            "                    opath.dirname(__file__), \"validators\", \"_validators.json\"\n"
            "                )\n"
            "                if not opath.exists(validator_json_path):\n"
            "                    raise FileNotFoundError(\n"
            "                        f\"Validator JSON file not found: {validator_json_path}\"\n"
            "                    )\n"
            "                with open(validator_json_path, \"r\") as f:\n"
            "                    ValidatorCache._json_cache = json.load(f)\n"
        )
        if new in text:
            return text
        if old not in text:
            raise RuntimeError("expected plotly validator JSON loader was not found")
        return text.replace(old, new, 1)

    transform_source_text(context, "Lib/plotly/validator_cache.py", patch_validator_cache, allow_missing=True)

    def patch_legacy_tools(text: str) -> str:
        if "_STATICPYTHON_PLOTLY_MIN_JS" in text:
            return text
        if "get_embed('plotly')" not in text:
            return text
        if "from plotly._staticpython_package_data import PLOTLY_MIN_JS as _STATICPYTHON_PLOTLY_MIN_JS" not in text:
            text = text.replace(
                "from plotly import exceptions, optional_imports\n",
                "from plotly import exceptions, optional_imports\n"
                "try:\n"
                "    from plotly._staticpython_package_data import PLOTLY_MIN_JS as _STATICPYTHON_PLOTLY_MIN_JS\n"
                "except Exception:\n"
                "    _STATICPYTHON_PLOTLY_MIN_JS = None\n",
                1,
            )
        updated, count = re.subn(
            r"""(?ms)^(\s*)path = os\.path\.join\('package_data', 'plotly\.min\.js'\)\n\s*plotlyjs = resource_string\('plotly', path\)\.decode\('utf-8'\)\n\s*return plotlyjs\n""",
            (
                "    path = os.path.join('package_data', 'plotly.min.js')\n"
                "    try:\n"
                "        plotlyjs_data = resource_string('plotly', path)\n"
                "    except Exception:\n"
                "        plotlyjs_data = None\n"
                "    if plotlyjs_data is not None:\n"
                "        return plotlyjs_data.decode('utf-8')\n"
                "    if _STATICPYTHON_PLOTLY_MIN_JS is not None:\n"
                "        return _STATICPYTHON_PLOTLY_MIN_JS\n"
                "    raise FileNotFoundError(path)\n"
            ),
            text,
            count=1,
        )
        if count == 1:
            return updated
        if "resource_string('plotly', path)" in text or "plotly.min.js" in text:
            raise RuntimeError("expected legacy plotly.min.js loader was not found")
        return text

    transform_first_existing_source_text(
        context,
        [
            "Lib/plotly/tools.py",
            "Lib/plotly/offline/offline.py",
        ],
        patch_legacy_tools,
        allow_all_missing=True,
    )
